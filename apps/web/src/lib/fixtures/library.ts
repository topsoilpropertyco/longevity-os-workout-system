/**
 * Demo exercise library.
 *
 * FIXTURE DATA ONLY — the real library is ingested into Supabase from
 * `yuhonas/free-exercise-db` + the Gym Visual media set. These entries exist so
 * every screen renders before the database is configured. Shapes are the
 * engine's `Exercise`; nothing here is engine logic.
 */

import type { Equipment, Exercise, MovementPattern, Region, RegionLoadMap } from '../engine-bridge';

type ExSpec = Partial<Exercise> & {
  slug: string;
  name: string;
  pattern: MovementPattern;
  equipment: Equipment[];
  region_loads: RegionLoadMap;
};

function ex(spec: ExSpec): Exercise {
  return {
    id: spec.slug,
    name: spec.name,
    slug: spec.slug,
    aliases: spec.aliases ?? [],
    pattern: spec.pattern,
    force: spec.force ?? 'push',
    mechanic: spec.mechanic ?? 'compound',
    level: spec.level ?? 'intermediate',
    equipment: spec.equipment,
    region_loads: spec.region_loads,
    load_style: spec.load_style ?? 'total_dumbbell_pair',
    barbell_free: spec.barbell_free ?? true,
    eccentric_dominant: spec.eccentric_dominant ?? false,
    plyo_contacts_per_rep: spec.plyo_contacts_per_rep ?? 0,
    instructions: spec.instructions ?? [],
    source: spec.source ?? 'curated',
    ...(spec.kot_step ? { kot_step: spec.kot_step } : {}),
    ...(spec.cue ? { cue: spec.cue } : {}),
    ...(spec.preferred_alternatives ? { preferred_alternatives: spec.preferred_alternatives } : {}),
    ...(spec.rehab_for ? { rehab_for: spec.rehab_for } : {}),
    ...(spec.media ? { media: spec.media } : {}),
  };
}

